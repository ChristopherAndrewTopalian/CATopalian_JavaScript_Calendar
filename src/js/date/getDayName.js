// gets day name from a date
function getDayName(date)
{
    let daysOfWeek = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

    return daysOfWeek[date.getDay()];
}

